CREATE TABLE IF NOT EXISTS membership_plans (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(100) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  price DECIMAL(10,2) NOT NULL,
  price_formatted VARCHAR(50) NOT NULL,
  period VARCHAR(50) NOT NULL DEFAULT '/ year',
  validity VARCHAR(100) NOT NULL DEFAULT '12 Months Validity',
  tagline VARCHAR(255) NULL,
  is_popular TINYINT(1) DEFAULT 0,
  features JSON NOT NULL,
  card_bg VARCHAR(255) NULL,
  pass_gradient VARCHAR(255) NULL,
  badge_style VARCHAR(255) NULL,
  button_style VARCHAR(255) NULL,
  accent_text VARCHAR(100) NULL,
  display_order INT DEFAULT 0,
  is_active TINYINT(1) DEFAULT 1,
  subscribers_count INT DEFAULT 18,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

